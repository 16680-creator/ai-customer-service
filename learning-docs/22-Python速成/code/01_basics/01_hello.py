"""01 · 第一个程序：和 Java 的 HelloWorld 对照

运行: python 01_basics/01_hello.py
"""

# ---------------------------------------------------------------------------
# Java:
#   public class Hello {
#       public static void main(String[] args) {
#           System.out.println("Hello, Python");
#       }
#   }
#
# Python: 没有类包裹，没有 main 方法，没有分号，没有大括号
# ---------------------------------------------------------------------------

# ---- 本段讲：最小的 Python 程序长什么样 ----
# 对比上面注释里的 Java：一个 println 需要 class + main + 分号 + 大括号；
# Python 是解释执行，文件从上到下逐行跑，这一行本身就是"入口"。
print("Hello, Python")   # 内置函数，等价 System.out.println(...)；自动换行，行尾不需要分号


# ---------------------------------------------------------------------------
# 顶层代码在 import 时也会执行 —— 所以要加这层保护
# ---------------------------------------------------------------------------

# ---- 本段讲：为什么要写 main()，以及 __main__ 保护的作用 ----
# Java 的 main 是 JVM 约定的入口，类被加载时不会自动执行方法体；
# Python 没有入口约定，别的文件 import 本模块时会把顶层代码全部执行一遍，
# 所以要用 if __name__ == "__main__" 把"只在直接运行时才执行"的代码圈起来。
def main() -> None:          # def 定义函数；-> None 是返回值注解（仅提示，运行时不检查）
    """真正的入口逻辑。被 import 时不会自动执行。"""
    print("-" * 40)          # "字符串 * 整数"表示重复拼接，等价 Java 里循环 append 40 个 '-'
    print("这段在 __main__ 保护里，被 import 时不会跑")

    name = "张三"            # 赋值即声明；Java 要写 String name = "张三";
    age = 30                 # 动态类型，赋值才确定类型；Java 要写 int age = 30;
    # f-string：等价于 Java 的 String.format
    print(f"{name} 今年 {age} 岁")   # f 前缀让 {} 里直接写变量/表达式，比 "..." + name + "..." 清晰


# 只有"直接运行本文件"时 __name__ 才是 "__main__"，被 import 时是模块名。
# 这一行等价于 Java 的 public static void main，但仅在本文件作为入口时成立。
if __name__ == "__main__":   # 双下划线是 Python 的"魔术名"，不是普通变量
    main()                   # 缩进 4 空格表示属于 if 块；Java 用大括号划定范围


# ---------------------------------------------------------------------------
# 模块身份演示
# ---------------------------------------------------------------------------
# ---- 本段讲：用 __name__ 和 sys.executable 观察"我以什么身份在跑" ----
# 直接运行时:  __name__ == "__main__"
# 被 import 时: __name__ == "01_hello"（模块名）
print(f"\n[模块身份] __name__ = {__name__}")   # \n 是换行转义，同 Java；__name__ 由解释器自动注入
print(f"[解释器]   {__import__('sys').executable}")   # __import__ 是动态版 import；sys.executable 返回当前解释器的绝对路径
