"""01 · 第一个程序：和 Java 的 HelloWorld 对照

运行: python 01_basics/01_hello.py
"""

# ---------------------------------------------------------------------------
# Java:
#   public class Hello {
#       public static void main(String[] args) {
#           System.out.println("Hello, Python");
#       }
#   }
#
# Python: 没有类包裹，没有 main 方法，没有分号，没有大括号
# ---------------------------------------------------------------------------

print("Hello, Python")


# ---------------------------------------------------------------------------
# 顶层代码在 import 时也会执行 —— 所以要加这层保护
# ---------------------------------------------------------------------------

def main() -> None:
    """真正的入口逻辑。被 import 时不会自动执行。"""
    print("-" * 40)
    print("这段在 __main__ 保护里，被 import 时不会跑")

    name = "张三"
    age = 30
    # f-string：等价于 Java 的 String.format
    print(f"{name} 今年 {age} 岁")


if __name__ == "__main__":
    main()


# ---------------------------------------------------------------------------
# 模块身份演示
# ---------------------------------------------------------------------------
# 直接运行时:  __name__ == "__main__"
# 被 import 时: __name__ == "01_hello"（模块名）
print(f"\n[模块身份] __name__ = {__name__}")
print(f"[解释器]   {__import__('sys').executable}")
